import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const id = 'post-fd-bgk-relaxation';
const prefix = 'research/fluid-dynamics-all-47-2026-10-23-batch-26';
// This script is invoked only inside step5-shared-write-lock run.
const item = readFileSync(`items/${id}.md`, 'utf8');
const statement = item.split('## Postulate\n\n')[1].split('\n## Postulate references')[0].trim();
assert(statement.startsWith('Adopt Countable Choice'));
const manifestPath = `${prefix}.pages.json`;
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const rows = manifest.flatMap(page => page.items).filter(row => row.id === id);
assert.equal(rows.length, 1);
const row = rows[0];
const oldStatement = row.statement;
assert.equal(statement.split('\n\n').slice(1).join('\n\n'), oldStatement);
row.statement = statement;
assert.equal(row.sources.references[0].locator, "Lecture 2, section II, 'The BGK Operator', PDF pp. 27–29; local Maxwellian relaxation with positive relaxation time.");
row.sources.references[0].locator = "Lecture 2, section V, 'The BGK Operator', PDF p. 28; local Maxwellian relaxation with positive relaxation time.";
const contractPath = `${prefix}.proof-contracts.json`;
const contracts = JSON.parse(readFileSync(contractPath, 'utf8'));
const review = contracts.contracts[id].physics_review;
assert(review.formulation.evidence.includes('moment-matched Maxwellian'));
review.formulation.evidence = 'The postulate explicitly adopts exactly the Countable Choice premise of def-fd-conserving-bgk and defines its indexed-family content. The admissible third-moment domain, positive number density and temperature, moment-matched Maxwellian, constant relaxation time, dimensionless fast scale, weighted C1 solution sense and common-full-measure pointwise sense agree with the current supplier. No stronger choice principle or solution-existence assertion is added.';
// Preserve the earlier source-reading attribution; append this owner's narrower check.
review.sources.evidence += ' Impact owner step5-v2-impact-initial-pass-2-r1-u1 independently checked Golse–Levermore Lecture 2 section V, PDF p. 28, and Tong section 2.5.1, printed pp. 46–47; the Golse locator is corrected from section II to section V. This is focused source/formulation review, not new fetch-stamp or proof-acceptance evidence.';
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(contractPath, JSON.stringify(contracts, null, 2) + '\n');
assert.equal(JSON.parse(readFileSync(manifestPath, 'utf8')).flatMap(p => p.items).find(r => r.id === id).statement, statement);
assert.equal(JSON.parse(readFileSync(contractPath, 'utf8')).contracts[id].physics_review.formulation.verdict, 'pass');
console.log('Scoped metadata updated: one postulate mirror/source locator and its nonproof formulation/source reviews.');
