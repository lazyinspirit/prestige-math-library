// Root execution only: authenticate existing native evidence, preserve originals.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { activeOwnershipRows } from '../tools/defect-ledger-ownership.mjs';
const run='numerical-optimization-dynamics-2026-10-16', p=`research/${run}`;
const read=x=>fs.readFileSync(x), json=x=>JSON.parse(read(x));
const sha=x=>createHash('sha256').update(x).digest('hex');
const canon=x=>Array.isArray(x)?x.map(canon):x&&typeof x==='object'?Object.fromEntries(Object.keys(x).sort().map(k=>[k,canon(x[k])])):x;
const hash=x=>sha(JSON.stringify(canon(x))??'undefined');
const assert=(x,msg)=>{if(!x)throw Error(msg);};
const semantic=({subject_sha256,...x})=>x;
const inventory=json(`${p}-ROOT-owner-evidence-inventory-r3.json`);
const group=inventory.groups.find(g=>g.group==='batch-105');
const get=o=>{const rows=group.targets.filter(x=>x.obligation===o);assert(rows.length===1,'Unique actual native target');return rows[0];};
const entry=json(`${p}-owner-unchanged-page-causal-code/entry-105.UNSEALED.json`);
const page=get(entry.obligation),cause=get(entry.cause.obligation);
assert(page.decisions.length===1&&cause.decisions.length===1,'Actual native decisions');
const post=json(entry.refs.post_snapshot.path);
assert(sha(read(entry.refs.cause_before.path))===post.hashes[entry.cause.id].item_sha256,'Authenticate full immutable POST cause-before source');
assert(read(entry.refs.page_source.path).equals(read(entry.current_path)),'Unchanged page archive current');
assert(read(entry.refs.cause_after.path).equals(read(entry.cause.current_path)),'Repaired cause archive current');
const rowsPath='research/defect-ledger.jsonl';
assert(fs.existsSync(rowsPath),'Actual native ledger path');
const errors=[];
const rows=activeOwnershipRows(read(rowsPath).toString().trim().split('\n').map(JSON.parse).filter(x=>x.run===run),errors);
assert(!errors.length,'Valid active ownership');
for(const [e,t] of [[entry,page],[entry.cause,cause]]){
  const row=rows.filter(r=>r.defect_id===e.defect_id);assert(row.length===1&&row[0].subject===e.id&&row[0].disposition==='fixed','Actual separate fixed row');
  e.current_raw_sha256=sha(read(e.current_path));e.target_sha256=hash(t.check_target);
  e.decision_sha256=hash(semantic(t.decisions[0].decision));e.ledger_row_sha256=hash(row[0]);
}
assert(page.decisions[0].current_equals_target_observation===true,'Original unchanged page carrier');
entry.cause.current_carrier_sha256=cause.decisions[0].current_carrier_sha256;
for(const ref of Object.values(entry.refs))ref.sha256=sha(read(ref.path));
const archivedRows=json(entry.refs.ledger_rows.path);
assert(archivedRows.length===2&&archivedRows.every(a=>rows.some(b=>hash(a)===hash(b))),'Archived actual active rows');
entry.reviewed=true;
entry.reason='Root authenticated the complete original locator source against the immutable native reader-post raw SHA256, current unchanged page and actual algorithm repair, genuine successful native105 result, assignment and explicit causal/current-page review. Both separate original fatal findings and fixed active ledger rows remain intact. This binding grants only unchanged-page causal repair continuity, never new review or acceptance.';
const evidencePath=`${p}-step3-owner-repair-evidence.json`, before=read(evidencePath), evidence=JSON.parse(before);
assert(evidence.version===1&&evidence.run===run&&evidence.prior_applied_repairs.length===2,'Preserve existing actual prior evidence');
assert(!evidence.source_identical_acceptance_continuities&&!evidence.unchanged_page_causal_repairs,'No overwrite');
const original=json(`${p}-ROOT-source-identical-continuity-proposed-r3/proposed-owner-evidence-fragment.json`);
assert(original.source_identical_acceptance_continuities.length===96,'All96 genuine original touched continuities');
evidence.source_identical_acceptance_continuities=original.source_identical_acceptance_continuities;
evidence.unchanged_page_causal_repairs=[entry];
const out=`${p}-ROOT-page105-continuity-sealing`;fs.mkdirSync(out);
fs.writeFileSync(`${out}/owner-evidence.before.json`,before);
fs.writeFileSync(`${out}/page105-sealed-entry.json`,JSON.stringify(entry,null,2)+'\n');
assert(read(evidencePath).equals(before),'Guard unchanged canonical authority');
fs.writeFileSync(evidencePath,JSON.stringify(evidence,null,2)+'\n');
fs.writeFileSync(`${out}/receipt.json`,JSON.stringify({version:1,run,recorded_at:new Date().toISOString(),reviewed_by:'/root',source_preimage_authenticated_raw_sha256:sha(read(entry.refs.cause_before.path)),owner_evidence_before_raw_sha256:sha(before),owner_evidence_current_raw_sha256:sha(read(evidencePath)),original_continuities:96,unchanged_page_causal_repairs:1,prior_applied_repairs_preserved:2,native_validation:'Not yet run; mandatory native battery remains owed.'},null,2)+'\n');
console.log(out);
