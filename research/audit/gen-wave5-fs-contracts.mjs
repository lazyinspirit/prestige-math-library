function overlapQuote(sectionText, factText) {
  const sentences = sectionText.split(/(?<=[.;:])\s+/).filter(s => s.length > 25 && s.length < 320);
  if (!sentences.length) return null;
  const toks = new Set(factText.toLowerCase().match(/[a-z]{4,}/g) || []);
  let best = null, bestScore = -1;
  for (const s of sentences) {
    const st = new Set(s.toLowerCase().match(/[a-z]{4,}/g) || []);
    let hit = 0; for (const t of st) if (toks.has(t)) hit++;
    const score = hit / Math.sqrt(st.size + 1);
    if (score > bestScore) { bestScore = score; best = s; }
  }
  return best;
}

