function sectionOf(id) {
  const t = fs.readFileSync(`items/${id}.md`, 'utf8');
  const body = t.split(/\n---\n/).slice(1).join('\n---\n');
  const m = body.match(SECTION_RE);
  return { name: m ? m[1] : 'Statement', text: (m ? m[0] : body).replace(/\s+/g, ' ').trim() };
}

