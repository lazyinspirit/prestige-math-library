// One-off read-only owner evidence check, not an engine protocol or gate.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const dir = dirname(fileURLToPath(import.meta.url));
const root = process.cwd();
const read = p => fs.readFileSync(resolve(root, p));
const sha = b => crypto.createHash('sha256').update(b).digest('hex');
const p = JSON.parse(fs.readFileSync(resolve(dir, 'owner-disposition.proposal.json')));
const bound = r => { const b = read(r.path); assert.equal(sha(b), r.sha256, r.path); return b; };
for (const r of p.immutable_original_evidence) bound(r);
for (const r of p.unchanged_page_items) bound(r);
bound(p.current_claim.theorem);
const b = bound(p.correction.before_archive), a = bound(p.correction.after_archive);
const text = b.toString();
assert.equal(text.split(p.correction.before).length, 2);
assert.equal(text.replace(p.correction.before, p.correction.after), a.toString());
const fm = text => text.match(/^---\n[\s\S]*?\n---\n/)[0];
assert.equal(fm(text), fm(a.toString()));
assert.equal(sha(fm(text)), p.correction.frontmatter_sha256);
const after = process.argv.includes('--after');
assert.deepEqual(read(p.source_path), after ? a : b, 'current page differs from exact proposed state');
const zeroWork = JSON.parse(read(`research/${p.run}-step5-v2/step5-v2-initial-r1-u12.json`));
assert.equal(zeroWork.completion, 'mechanical-zero-work');
assert.equal(zeroWork.mathematical_review, false);
assert.equal(zeroWork.reviews.length, 0);
console.log(`Verified exact ${after ? 'applied' : 'pre-application'} page state, one prose replacement, unchanged metadata/items, and immutable original evidence; no native review claimed.`);
